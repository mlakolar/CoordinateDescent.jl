 fit(A,rnorm(80));warnings=character();gc();t=proc.time()[[3]];ans=fit(X,y);elapsed=proc.time()[[3]]-t
 if(engine=='sslasso'){
   G=crossprod(X)/nrow(X);gaps=rowSums((ans%*%G)*ans)-diag(ans)+mu*rowSums(abs(ans))
   gap=max(abs(gaps));resid=max(abs(ans%*%G-diag(ncol(X))))
   write.table(ans,paste0(out,'-theta.csv'),sep=',',row.names=FALSE,col.names=FALSE)
   list(status=if(gap<1e-6 && resid<=mu+1e-6)'ok' else 'invalid',fit_seconds=elapsed,qp_gap=gap,qp_residual=resid,targets=nrow(ans))
 }else{
   write.table(ans,paste0(out,'-coef.csv'),sep=',',row.names=FALSE,col.names=FALSE)
   list(status='ok',fit_seconds=elapsed,targets=nrow(ans))
 }
},warning=function(w){warnings<<-c(warnings,conditionMessage(w));invokeRestart('muffleWarning')}),error=function(e)list(status='error',error=conditionMessage(e)))
r$warnings=paste(unique(warnings),collapse=' | ')
writeLines(paste(names(r),unlist(r),sep='='),paste0(out,'.meta'))
