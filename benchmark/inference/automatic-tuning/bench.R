args=commandArgs(TRUE);engine=args[1];label=args[2];rep=args[3]
.libPaths(c('/home1/mkolar/juliaPkg/runs/20261025-cd77-comparison-pilot/Rlib','/home1/mkolar/juliaPkg/runs/20261025-cd77-inference/Rlib','/home1/mkolar/juliaPkg/Rlib-cd-r4.5.3','/home1/mkolar/juliaPkg/Rlib-r4.5.3',.libPaths()))
suppressPackageStartupMessages(library(glmnet))
base=file.path('bench-data',label,rep);out=file.path('bench',paste(args,collapse='-'))
X=as.matrix(read.csv(file.path(base,'X.csv'),header=FALSE));y=scan(file.path(base,'y.csv'),quiet=TRUE)
c=read.csv(file.path(base,'config.csv'));lambda=c$lambda_main;node=c$lambda_node;mu=c$mu
if(engine=='hdi')suppressPackageStartupMessages(library(hdi))
if(engine=='SIHR')suppressPackageStartupMessages(library(SIHR))
if(engine=='sslasso'){
 src=readLines('/home1/mkolar/juliaPkg/runs/20261025-cd77-inference/references/sslasso_code/lasso_inference.r')
 a=grep('if (mu >= mu0)',src,fixed=TRUE);stopifnot(length(a)==1)
 src[a+1]=sub('(1-mu0)','(1-mu)',src[a+1],fixed=TRUE)
 eval(parse(text=src[!grepl('^library',src)]))
}
fit=function(A,b){
 p=ncol(A);n=nrow(A)
 if(engine=='sslasso'){
   G=crossprod(A)/n
   return(t(vapply(seq_len(p),function(j)InverseLinftyOneRow(G,j,mu,maxiter=100000,threshold=1e-10)$optsol,numeric(p))))
 }
 if(engine=='hdi'){
  g=glmnet(A,b,lambda=lambda,standardize=FALSE,intercept=TRUE,thresh=1e-12,maxit=100000)
  beta=as.vector(coef(g))[-1];res=b-as.vector(predict(g,A));sd=sqrt(sum(res^2)/(n-sum(beta!=0)-1))
  Z=vapply(seq_len(p),function(j){
    f=glmnet(A[,-j,drop=FALSE],A[,j],lambda=node,standardize=FALSE,intercept=FALSE,thresh=1e-12,maxit=100000)
    A[,j]-as.vector(predict(f,A[,-j,drop=FALSE]))
  },numeric(n))
  f=hdi::lasso.proj(A,b,standardize=FALSE,betainit=beta,sigma=sd,Z=Z,suppress.grouptesting=TRUE)
  return(cbind(f$bhat,f$se))
 }
 if(engine=='SIHR'){
   L=diag(p)[,1:10,drop=FALSE]
   f=SIHR::LF(A,b,loading.mat=L,model='linear',lambda=lambda,mu=mu)
   return(cbind(f$est.debias.vec,f$se.vec))
 }
}
warnings=character()
